def cast_dirs():
    """Two-tier cast library: channel first, then every episode's assets/cast (episode-only characters)."""
    dirs = [CAST]
    if os.path.isdir(PROJECTS):
        for ep in sorted(os.listdir(PROJECTS)):
            d = os.path.join(PROJECTS, ep, "assets", "cast")
            if os.path.isdir(d):
                dirs.append(d)
    return dirs


def cast_recipe_files():
    """{id: path} for every minifig recipe across both tiers (channel wins on id clashes)."""
    out = {}
    for d in cast_dirs():
        for fn in sorted(os.listdir(d)):
            if fn.endswith(".json") and fn[:-5] not in out:
                out[fn[:-5]] = os.path.join(d, fn)
    return out
